/**
 * Drop-in replacements for Material 3's four button composables, identical in signature but with
 * **the house border on by default**.
 *
 * Upstream draws an action as bare text — the 「付与」 buttons down the right of the permissions
 * page, dialog confirms, "Update all", and so on — which on our black ground reads as floating
 * words rather than as something to press. Every one of them is a pill with a yellow outline here.
 *
 * A file switches over by importing these instead of the `androidx.compose.material3` ones; there
 * is nothing to change at the call sites, and buttons added upstream later inherit the styling as
 * soon as their file is switched over.
 *
 * The border follows the UI page's own knobs, so a border width of 0 really means "no border"
 * everywhere, exactly as the slider says.
 */
@Composable
fun houseButtonBorder(): BorderStroke? {
    val ui = LocalMiseUi.current
    if (ui.borderWidth <= 0) return null
    return BorderStroke(ui.borderWidth.dp, Color(ui.borderColor))
}

@Composable
fun TextButton(
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    enabled: Boolean = true,
    shape: Shape = ButtonDefaults.textShape,
    colors: ButtonColors = ButtonDefaults.textButtonColors(),
    elevation: ButtonElevation? = null,
    border: BorderStroke? = houseButtonBorder(),
    contentPadding: PaddingValues = ButtonDefaults.TextButtonContentPadding,
    interactionSource: MutableInteractionSource? = null,
    content: @Composable RowScope.() -> Unit
) = androidx.compose.material3.TextButton(
    onClick = onClick,
    modifier = modifier,
    enabled = enabled,
    shape = shape,
    colors = colors,
    elevation = elevation,
    border = border,
    contentPadding = contentPadding,
    interactionSource = interactionSource,
    content = content
)

